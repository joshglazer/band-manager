-- ============================================================
-- Tables (ordered by dependency)
-- ============================================================

create table if not exists public.bands (
  id         bigint generated by default as identity primary key,
  name       text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.band_members (
  id         bigint generated by default as identity primary key,
  band_id    bigint not null references public.bands (id) on delete cascade,
  user_id    uuid not null references auth.users (id) on delete cascade,
  instrument text,
  created_at timestamptz not null default now()
);

create table if not exists public.songs (
  id         bigint generated by default as identity primary key,
  band_id    bigint not null references public.bands (id) on delete cascade,
  name       text,
  artist     text,
  duration   integer,
  created_at timestamptz not null default now()
);

create table if not exists public.setlists (
  id         bigint generated by default as identity primary key,
  band_id    bigint not null references public.bands (id) on delete cascade,
  name       text,
  created_at timestamptz not null default now()
);

create table if not exists public.setlist_songs (
  id         bigint generated by default as identity primary key,
  setlist_id bigint not null references public.setlists (id) on delete cascade,
  song_id    bigint not null references public.songs (id) on delete cascade,
  set        integer not null,
  set_weight integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.comment_types (
  id         bigint generated by default as identity primary key,
  label      text,
  created_at timestamptz not null default now()
);

create table if not exists public.song_comments (
  id              bigint generated by default as identity primary key,
  song_id         bigint not null references public.songs (id) on delete cascade,
  user_id         uuid not null references auth.users (id) on delete cascade,
  comment_type_id bigint references public.comment_types (id) on delete set null,
  comment         text,
  created_at      timestamptz not null default now()
);

create table if not exists public.user_profiles (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  first_name text,
  last_name  text,
  bio        text,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Functions
-- ============================================================

create or replace function public.is_band_member(band_id_arg bigint)
returns boolean
language sql
security definer
stable
as $$
  select exists (
    select 1
    from public.band_members
    where band_id = band_id_arg
      and user_id = auth.uid()
  );
$$;

