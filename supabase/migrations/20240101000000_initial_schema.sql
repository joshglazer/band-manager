-- bands: band members can read; any authenticated user can create
create policy "band members can view their bands"
  on public.bands for select
  to authenticated
  using (public.is_band_member(id));

create policy "authenticated users can create bands"
  on public.bands for insert
  to authenticated
  with check (true);

-- band_members: members of the band can view; authenticated users can join
create policy "band members can view members"
  on public.band_members for select
  to authenticated
  using (public.is_band_member(band_id));

create policy "authenticated users can join bands"
  on public.band_members for insert
  to authenticated
  with check (auth.uid() = user_id);

